// HostAuditMarkdown generates a comprehensive, AI-agent-ready and security-expert-ready
// Markdown report containing full system context, forensic evidence, and remediation steps.
func HostAuditMarkdown(r *model.Report) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Host Security Audit Report: `%s`\n\n", r.Host)

	b.WriteString("## 1. System & Scan Context\n\n")
	b.WriteString("| Property | Value |\n|---|---|\n")
	fmt.Fprintf(&b, "| **Host** | `%s` |\n", r.Host)
	fmt.Fprintf(&b, "| **Operating System** | %s |\n", r.OS)
	fmt.Fprintf(&b, "| **Kernel** | `%s` |\n", r.Kernel)
	fmt.Fprintf(&b, "| **Scanner** | `%s %s` |\n", r.Tool, r.Version)
	fmt.Fprintf(&b, "| **Timestamp** | %s |\n", r.StartedAt.Format(time.RFC3339))
	fmt.Fprintf(&b, "| **Duration** | %.2fs |\n", float64(r.DurationMS)/1000)
	fmt.Fprintf(&b, "| **Privileges** | root=%v |\n", r.Root)
	fmt.Fprintf(&b, "| **Security Score** | **Grade %s (%d/100)** |\n", r.Grade, r.ScoreVal)
	fmt.Fprintf(&b, "| **Check Coverage** | %s |\n", r.Coverage)
	fmt.Fprintf(&b, "| **Findings Summary** | Critical: %d, High: %d, Medium: %d, Low: %d, Info: %d, Suppressed: %d |\n\n",
		r.Counts["critical"], r.Counts["high"], r.Counts["medium"], r.Counts["low"], r.Counts["info"], r.Suppressed)

	if r.GradeNote != "" {
		fmt.Fprintf(&b, "> **Coverage Warning:** %s\n>\n", r.GradeNote)
		for _, inc := range r.Incomplete {
			fmt.Fprintf(&b, "> - Incomplete check: %s\n", inc)
		}
		b.WriteString("\n")
	}

	b.WriteString("## 2. Instructions for AI Assistants & Security Engineers\n\n")
	b.WriteString("This report was generated by `secscan` for automated or expert-assisted remediation. When analyzing or fixing these issues:\n\n")
	b.WriteString("1. **Prioritize by Severity:** Address `CRITICAL` and `HIGH` findings immediately before `MEDIUM` or `LOW` hardening items.\n")
	b.WriteString("2. **Preserve Evidence for Malware/Persistence:** If `MAL-*`, `PERSIST-UNIT-DISGUISED`, `PROC-MALICIOUS-SCRIPT`, or `PROC-HIDDEN-PID` appear, copy suspicious files to a non-executable quarantine folder (`chmod a-x`) before deleting, then disable persistence and rotate credentials.\n")
	b.WriteString("3. **Verify Before Modifying System Services:** For `NET-LISTEN-*` or `HARD-SYSCTL`, confirm whether the service is intentionally exposed or required (e.g., Docker networking) before disabling or binding to `127.0.0.1`.\n")
	b.WriteString("4. **Re-verify After Remediation:** Run `sudo secscan` after applying fixes to confirm findings are resolved and the score improves.\n\n")

	b.WriteString("## 3. Prioritized Action Plan\n\n")
	now, soon, later := r.ActionPlan()
	for _, g := range []struct {
		t  string
		it []string
	}{
		{"Immediate (CRITICAL / HIGH)", now},
		{"Short-Term (MEDIUM)", soon},
		{"Hardening (LOW)", later},
	} {
		if len(g.it) == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n", g.t)
		for _, x := range g.it {
			fmt.Fprintf(&b, "- [ ] %s\n", x)
		}
		b.WriteString("\n")
	}
	if len(now)+len(soon)+len(later) == 0 {
		b.WriteString("No actionable findings detected.\n\n")
	}

	b.WriteString("## 4. Detailed Findings (Full Forensic Evidence)\n\n")
	findings := r.AllFindings(false)
	if len(findings) == 0 {
		b.WriteString("No unsuppressed findings were recorded.\n\n")
	}
	for idx, f := range findings {
		st := ""
		if f.Status == "new" {
			st = " **[NEW]**"
		}
		fmt.Fprintf(&b, "### %d. [%s] `%s` — %s%s\n\n", idx+1, f.Severity, f.ID, f.Title, st)
		fmt.Fprintf(&b, "- **Check Module:** `%s`\n", f.Check)
		fmt.Fprintf(&b, "- **Category:** %s\n", f.Category)
		fmt.Fprintf(&b, "- **Fingerprint:** `%s`\n", f.Fingerprint)
		if f.Detail != "" {
			fmt.Fprintf(&b, "- **Risk & Context:** %s\n", f.Detail)
		}
		b.WriteString("\n")
		if len(f.Evidence) > 0 {
			b.WriteString("**Forensic Evidence:**\n\n```text\n")
			b.WriteString(strings.Join(f.Evidence, "\n"))
			b.WriteString("\n```\n\n")
		}
		if f.Remediation != "" {
			b.WriteString("**Recommended Remediation:**\n\n```bash\n")
			b.WriteString(f.Remediation)
			b.WriteString("\n```\n\n")
		}
	}

	if len(r.Resolved) > 0 {
		b.WriteString("## 5. Resolved Since Previous Run\n\n")
		for _, res := range r.Resolved {
			fmt.Fprintf(&b, "- [x] %s\n", res)
		}
		b.WriteString("\n")
	}

	b.WriteString("## 6. Check Execution Matrix\n\n")
	b.WriteString("| Check ID | Name | Category | Status | Duration | Note |\n|---|---|---|---|---|---|\n")
	for _, res := range r.Results {
		note := strings.ReplaceAll(res.Note, "|", "\\|")
		fmt.Fprintf(&b, "| `%s` | %s | %s | `%s` | %.2fs | %s |\n",
			res.ID, res.Name, res.Category, res.Status, float64(res.DurationMS)/1000, note)
	}
	return b.String()
}

// CodeScanMarkdown generates a comprehensive, AI-agent-ready and security-expert-ready
// Markdown report for a static codebase or ZIP archive malware scan.
func CodeScanMarkdown(rep *model.CodeScanReport) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Codebase & Archive Malware Scan Report: `%s`\n\n", filepath.Base(rep.Target))

	b.WriteString("## 1. Scan Context & Verdict\n\n")
	b.WriteString("| Property | Value |\n|---|---|\n")
	fmt.Fprintf(&b, "| **Target** | `%s` |\n", rep.Target)
	fmt.Fprintf(&b, "| **Scanner Engine** | %s |\n", rep.Scanner)
	fmt.Fprintf(&b, "| **Files Scanned** | %d |\n", rep.FilesScanned)
	fmt.Fprintf(&b, "| **Scan Duration** | %.2fs |\n", rep.Seconds)
	fmt.Fprintf(&b, "| **Verdict** | **%s** |\n", strings.ToUpper(strings.ReplaceAll(rep.Verdict, "_", " ")))
	fmt.Fprintf(&b, "| **Severity Counts** | Critical: %d, High: %d, Medium: %d, Low: %d, Info: %d |\n\n",
		rep.CountsBySeverity["critical"], rep.CountsBySeverity["high"],
		rep.CountsBySeverity["medium"], rep.CountsBySeverity["low"], rep.CountsBySeverity["info"])

	if len(rep.CountsByCategory) > 0 {
		cats := make([]string, 0, len(rep.CountsByCategory))
		for c := range rep.CountsByCategory {
			cats = append(cats, c)
		}
		sort.Strings(cats)
		b.WriteString("**Detections by Category:** ")
		for i, c := range cats {
			if i > 0 {
				b.WriteString(" | ")
			}
			fmt.Fprintf(&b, "`%s`: %d", c, rep.CountsByCategory[c])
		}
		b.WriteString("\n\n")
	}

	b.WriteString("## 2. Instructions for AI Assistants & Security Engineers\n\n")
	b.WriteString("This report was produced by `secscan code-scan` using **read-only static pattern and co-occurrence analysis** (no target code was executed, imported, or built).\n\n")
	b.WriteString("When reviewing this report:\n")
	b.WriteString("1. **Do NOT execute or install dependencies** (`npm install`, `pip install`, `cargo build`, `make`) until every `CRITICAL` and `HIGH` finding is inspected and explained.\n")
	b.WriteString("2. **Distinguish True Positives from Legitimate Patterns:** Security scanners, regex rule files, test fixtures, or minified bundles may trigger pattern matches. Inspect the exact `file:line` and surrounding context in the target codebase.\n")
	b.WriteString("3. **Pay Special Attention to Supply-Chain & Co-Occurrence Rules:** `npm-lifecycle` (`preinstall`/`postinstall`), `clip-hijack-combo`, `rs-*-socket-shell`, `src-bidi` (Trojan Source), and `zip-encrypted-payload` are high-signal indicators.\n\n")

	b.WriteString("## 3. Findings Overview\n\n")
	if len(rep.Findings) == 0 {
		b.WriteString("No malware indicators were detected by static pattern analysis.\n\n")
	} else {
		b.WriteString("| # | Severity | Rule | Category | Location |\n|---|---|---|---|---|\n")
		for idx, f := range rep.Findings {
			loc := f.File
			if f.Line > 0 {
				loc = fmt.Sprintf("%s:%d", f.File, f.Line)
			}
			fmt.Fprintf(&b, "| %d | **%s** | `%s` | `%s` | `%s` |\n", idx+1, f.Severity, f.Rule, f.Category, loc)
		}
		b.WriteString("\n")

		b.WriteString("## 4. Detailed Findings & Investigation Guide\n\n")
		for idx, f := range rep.Findings {
			loc := f.File
			if f.Line > 0 {
				loc = fmt.Sprintf("%s:%d", f.File, f.Line)
			}
			fmt.Fprintf(&b, "### %d. [%s] `%s` (`%s`)\n\n", idx+1, f.Severity, f.Rule, loc)
			fmt.Fprintf(&b, "- **Category:** `%s`\n", f.Category)
			fmt.Fprintf(&b, "- **File:** `%s`\n", f.File)
			if f.Line > 0 {
				fmt.Fprintf(&b, "- **Line:** %d\n", f.Line)
			}
			fmt.Fprintf(&b, "- **Why Flagged:** %s\n", f.Why)
			fmt.Fprintf(&b, "- **Investigation / Action:** %s\n\n", codeScanGuidance(f.Category, f.Rule))
			if f.Evidence != "" {
				b.WriteString("**Matched Code / Artifact Evidence:**\n\n```text\n")
				b.WriteString(f.Evidence)
				b.WriteString("\n```\n\n")
			}
		}
	}

	if len(rep.Symlinks) > 0 {
		b.WriteString("## 5. Symlinks Not Followed\n\n```text\n")
		b.WriteString(strings.Join(rep.Symlinks, "\n"))
		b.WriteString("\n```\n\n")
	}

	if len(rep.Skipped) > 0 {
		b.WriteString("## 6. Skipped Files\n\n```text\n")
		b.WriteString(strings.Join(rep.Skipped, "\n"))
		b.WriteString("\n```\n\n")
	}

	b.WriteString("## Limitations\n\n")
	b.WriteString("Static pattern analysis only. `'no_indicators_found'` is **NOT** proof that the code is safe. Heavily obfuscated, encrypted, or dynamically fetched runtime payloads may evade static rules.\n")
	return b.String()
}

func codeScanGuidance(category, rule string) string {
	if rule == "zip-encrypted-payload" {
		return "Re-run `secscan code-scan` with the archive password (`--password` or interactive prompt) so encrypted entries can be inspected in memory."
	}
	if rule == "src-bidi" {
		return "Inspect the line in a hex/raw editor for hidden Unicode bidirectional control characters (`U+202A..U+202E`, `U+2066..U+2069`) that disguise malicious logic."
	}
	switch category {
	case "reverse_shell":
		return "Inspect the file for unauthorized outbound socket connections piped to `/bin/sh`, `bash`, `cmd.exe`, or PowerShell. Do not execute this file."
	case "clipboard_hijack":
		return "Check whether the code polls the OS clipboard, matches cryptocurrency wallet regexes, and silently replaces copied addresses."
	case "supply_chain":
		return "Review `package.json` install hooks (`preinstall`, `install`, `postinstall`). Run `npm install --ignore-scripts` only after verifying safety."
	case "exfiltration":
		return "Verify whether the code reads browser credential stores, SSH/AWS keys, or crypto wallets and transmits them to webhooks/Telegram/remote endpoints."
	case "rootkit":
		return "Inspect for `LD_PRELOAD`, kernel syscall hooking, or hidden process/file manipulation. Never load or compile untrusted kernel modules."
	case "obfuscation":
		return "Decode base64/hex/eval payloads statically in an isolated environment before trusting the file."
	case "miner":
		return "Remove unauthorized cryptominer binaries or stratum pool connections."
	case "binary":
		return "Verify the SHA-256 hash of compiled binaries against reproducible builds or official upstream releases."
	default:
		return "Inspect the referenced file and line manually to confirm whether the behavior is legitimate."
	}
}
